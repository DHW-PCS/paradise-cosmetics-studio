// Command assetgen builds frontend URLs from the same Go route catalog as HTTP.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"blessing-skin-go/internal/routes"
)

func main() {
	tree := map[string]any{}
	for _, route := range routes.Catalog {
		parts := strings.Split(route.Name, ".")
		if !strings.Contains("|auth|user|skinlib|texture|admin|", "|"+parts[0]+"|") || parts[len(parts)-1] == "" {
			continue
		}
		branch := tree
		for _, part := range parts[:len(parts)-1] {
			if branch[part] == nil {
				branch[part] = map[string]any{}
			}
			branch = branch[part].(map[string]any)
		}
		branch[parts[len(parts)-1]] = route.Path
	}
	code := "// Generated by go run ./cmd/assetgen.\nexport default " + render(tree) + "\n"
	if err := os.WriteFile("web/frontend/resources/assets/src/scripts/urls.ts", []byte(code), 0644); err != nil {
		panic(err)
	}
}

var parameter = regexp.MustCompile(`\{([a-zA-Z_]+)\??\}`)

func render(tree map[string]any) string {
	keys := make([]string, 0, len(tree))
	for key := range tree {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var fields []string
	for _, key := range keys {
		var expression string
		if child, ok := tree[key].(map[string]any); ok {
			expression = render(child)
		} else {
			path := tree[key].(string)
			var args []string
			for _, match := range parameter.FindAllStringSubmatch(path, -1) {
				args = append(args, match[1]+": string | number")
			}
			if len(args) == 0 {
				b, _ := json.Marshal(path)
				expression = "() => " + string(b) + " as const"
			} else {
				path = parameter.ReplaceAllString(path, `${encodeURIComponent(String($1))}`)
				expression = "(" + strings.Join(args, ",") + ") => `" + path + "`"
			}
		}
		fields = append(fields, fmt.Sprintf("%s: %s", strconv.Quote(key), expression))
	}
	return "{\n" + strings.Join(fields, ",\n") + "\n}"
}
